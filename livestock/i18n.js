window.HC = window.HC || {};
window.HC.lang = localStorage.getItem('hc.lang') || (navigator.language || 'en').slice(0, 2);
if (!window.HC_I18N[window.HC.lang]) window.HC.lang = 'en';

window.HC.t = function(key) {
  const dict = window.HC_I18N[window.HC.lang] || window.HC_I18N.en;
  return dict[key] || window.HC_I18N.en[key] || key;
};

window.HC.setLang = function(lang) {
  if (!window.HC_I18N[lang]) return;
  window.HC.lang = lang;
  localStorage.setItem('hc.lang', lang);
  window.HC.applyI18n();
  if (typeof window.HC.onLangChange === 'function') window.HC.onLangChange();
};

window.HC.applyI18n = function() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = window.HC.t(key);
    if (val.includes('<')) el.innerHTML = val;
    else el.textContent = val;
  });
  const langBtn = document.getElementById('lang-btn');
  if (langBtn) langBtn.textContent = window.HC.lang.toUpperCase();
  const langSel = document.getElementById('settings-lang');
  if (langSel) langSel.value = window.HC.lang;
  document.documentElement.lang = window.HC.lang;
};
